FROM_HERE = "github.event_name == 'push' || github.event.pull_request.head.repo.fork"
PROPRIETARY = "vars.DBT_LSP_PLUS_PROPRIETARY == 'true' && github.event_name == 'push'"
# A job, not one of its steps, that may fail without failing the run.
JOB_MAY_FAIL = r"(?m)^    continue-on-error: true$"
CARGO_CACHE = ["~/.cargo/registry", "~/.cargo/git", "target"]
CD_GATE = """    if: >-
      !github.event.repository.fork && (
        (github.event_name == 'workflow_dispatch' && github.ref == 'refs/heads/main') ||
        (github.event.workflow_run.conclusion == 'success' &&
         github.event.workflow_run.event == 'push' &&
         github.event.workflow_run.head_repository.full_name == github.repository)
      )
"""


def jobs_of(workflow):
    """Each job of the text of WORKFLOW, by name: the lines indented under it."""
    body = workflow[workflow.index("\njobs:\n") :]
    return {
        match[1]: match[2] for match in re.finditer(r"(?m)^  ([\w-]+):\n((?:(?:    .*)?\n)*)", body)
    }


class Workflows(unittest.TestCase):
    """What ties the workflows to the script and to the checks, as no local run can trigger them."""

    def setUp(self):
        self.cd = (ROOT / ".github/workflows/cd.yml").read_text()
        self.ci = (ROOT / ".github/workflows/ci.yml").read_text()
        self.weekly = (ROOT / ".github/workflows/weekly.yml").read_text()
        self.jobs = jobs_of(self.ci)

    def test_ci_has_the_jobs_of_plan_024(self):
        self.assertEqual(sorted(self.jobs), ["dbt", "dbt-oss", "macos", "static", "test"])

    def test_ci_checks_a_push_or_a_fork_s_pull_request_and_the_proprietary_build_when_asked(self):
        for name, job in self.jobs.items():
            with self.subTest(name):
                condition = PROPRIETARY if name == "dbt" else FROM_HERE
                self.assertRegex(job, rf"(?m)^    if: {re.escape(condition)}$")

    def test_ci_lets_only_macos_and_the_proprietary_build_fail(self):
        failing = sorted(name for name, job in self.jobs.items() if re.search(JOB_MAY_FAIL, job))
        self.assertEqual(failing, ["dbt", "macos"])
        self.assertEqual(self.ci.count("continue-on-error"), 2)

    def test_ci_runs_the_checks_of_the_makefile(self):
        for name, command in (
            ("static", "nix develop -c make check-static"),
            ("static", "nix develop -c make commits BASE=origin/main"),
            ("test", "nix develop -c make test"),
            ("macos", "nix develop -c make test"),
            ("dbt-oss", "nix develop -c make conformance"),
            ("dbt", "nix develop -c make conformance"),
            ("dbt", "nix develop -c unshare -rn make live"),
        ):
            with self.subTest(name=name, command=command):
                self.assertIn(f"run: {command}", self.jobs[name])

    def test_each_dbt_job_cuts_the_network_before_its_corpus(self):
        for name, build in (("dbt-oss", "oss"), ("dbt", "proprietary")):
            with self.subTest(name):
                job = self.jobs[name]
                steps = [
                    f"      - run: python3 scripts/fetch-dbt {build} ",
                    "      - run: sudo sysctl -w kernel.apparmor_restrict_unprivileged_userns=0\n",
                    "      - run: unshare -rn true\n",
                    "      - run: nix develop -c make conformance ",
                ]
                places = [job.find(step) for step in steps]
                self.assertNotIn(-1, places)
                self.assertEqual(places, sorted(places))

    def test_the_proprietary_corpus_runs_before_the_live_test_built_then_cut_off(self):
        job = self.jobs["dbt"]
        corpus = job.index("run: nix develop -c make conformance ")
        built = job.index("run: nix develop -c cargo test --locked --test proxy --no-run")
        self.assertLess(corpus, built)
        self.assertLess(built, job.index("run: nix develop -c unshare -rn make live "))

    def test_no_cache_holds_a_fetched_dbt(self):
        for name, job in self.jobs.items():
            with self.subTest(name):
                self.assertEqual(job.count("uses: actions/cache@"), 1)
                self.assertNotIn("paths:", job)
                blocks = re.findall(r"path: \|\n((?: {12}.*\n)+)", job)
                self.assertEqual([block.split() for block in blocks], [CARGO_CACHE])
                inline = re.findall(r"(?m)^ +path: (?!\|)(.+)$", job)
                self.assertEqual(inline, [])

    def test_ci_keys_each_cargo_cache_on_its_job_and_its_lock_files(self):
        for name, job in self.jobs.items():
            with self.subTest(name):
                key = re.search(r"(?m)^          key: (.+)$", job)[1]
                prefix = re.search(r"restore-keys: (.+)", job)[1]
                self.assertIn("github.job", key)
                self.assertIn("hashFiles('Cargo.lock', 'flake.lock')", key)
                self.assertTrue(key.startswith(prefix))

    def test_cd_gives_the_script_what_the_runner_does_not(self):
        for name in (
            "GH_TOKEN",
            *(name for name in release.SETTINGS if not name.startswith("GITHUB_")),
        ):
            with self.subTest(name):
                self.assertRegex(self.cd, rf"(?m)^ +{name}: ")

    def test_cd_raises_the_patch_part_unless_asked_by_hand(self):
        self.assertIn("RELEASE_BUMP: ${{ inputs.bump || 'patch' }}", self.cd)

    def test_cd_goes_on_only_after_a_success_of_a_push_here_or_by_hand_on_main(self):
        self.assertIn(CD_GATE, self.cd)

    def test_cd_releases_the_commit_that_ci_checked_one_run_at_a_time_never_cancelled(self):
        self.assertIn(
            "RELEASE_COMMIT: ${{ github.event.workflow_run.head_sha || github.sha }}", self.cd
        )
        self.assertRegex(self.cd, r"(?m)^  group: release\n  cancel-in-progress: false$")

    def test_ci_may_only_read(self):
        self.assertRegex(self.ci, r"(?m)^permissions:\n  contents: read\n\n")

    def test_cd_may_read_the_runs_of_ci_and_write_a_release(self):
        self.assertRegex(self.cd, r"(?m)^  actions: read$")
        self.assertRegex(self.cd, r"(?m)^  contents: write$")

    def test_cd_checks_out_what_ci_checked_and_follows_the_workflow_named_ci(self):
        self.assertRegex(
            self.cd, r"ref: \$\{\{ github\.event\.workflow_run\.head_sha \|\| github\.sha \}\}"
        )
        self.assertRegex(self.cd, r"workflows: \[CI\]")
        self.assertRegex(self.ci, r"(?m)^name: CI$")

    def test_every_action_is_pinned_by_a_full_commit(self):
        for text in (self.ci, self.cd, self.weekly):
            uses = re.findall(r"uses: (\S+)( # v\S+)?", text)
            self.assertTrue(uses)
            for action, version in uses:
                with self.subTest(action):
                    self.assertRegex(action, r"@[0-9a-f]{40}$")
                    self.assertTrue(version)

    def test_ci_trusts_no_other_cache(self):
        for word in ("substituters", "accept-flake-config"):
            with self.subTest(word):
                self.assertNotIn(word, self.ci)

    def test_ci_restores_the_store_between_the_installer_and_the_first_shell(self):
        for name, job in self.jobs.items():
            with self.subTest(name):
                installer = job.index("uses: cachix/install-nix-action@")
                cache = job.index("uses: nix-community/cache-nix-action@")
                self.assertLess(installer, cache)
                self.assertLess(cache, job.index("run: nix develop"))

    def test_ci_keys_the_store_on_the_flake_and_on_a_prefix_of_that_key(self):
        for name, job in self.jobs.items():
            with self.subTest(name):
                key = re.search(r"primary-key: (.+)", job)[1]
                prefix = re.search(r"restore-prefixes-first-match: (.+)", job)[1]
                self.assertIn("hashFiles('flake.nix', 'flake.lock')", key)
                self.assertTrue(key.startswith(prefix))


class Weekly(unittest.TestCase):
    """The weekly runs on the latest dbt, as plan 014 decides them."""

    def setUp(self):
        self.weekly = (ROOT / ".github/workflows/weekly.yml").read_text()
        self.weekly_jobs = jobs_of(self.weekly)

    def test_runs_each_monday_off_the_hour_and_by_hand_only(self):
        triggers = self.weekly[self.weekly.index("\non:\n") : self.weekly.index("\npermissions:")]
        self.assertEqual(re.findall(r"(?m)^  ([\w-]+):", triggers), ["schedule", "workflow_dispatch"])
        self.assertEqual(re.findall(r"cron: (.*)", self.weekly), ['"17 6 * * 1"'])

    def test_may_only_read_and_stands_alone(self):
        self.assertRegex(self.weekly, r"(?m)^permissions:\n  contents: read\n\n")
        self.assertEqual(self.weekly.count("permissions:"), 1)
        self.assertNotIn("concurrency:", self.weekly)

    def test_has_the_two_builds_and_fails_on_any_failure(self):
        self.assertEqual(sorted(self.weekly_jobs), ["dbt", "dbt-oss"])
        self.assertNotRegex(self.weekly, r"(?m)^ +continue-on-error:")
        gate = re.escape("vars.DBT_LSP_PLUS_PROPRIETARY == 'true'")
        self.assertRegex(self.weekly_jobs["dbt"], rf"(?m)^    if: {gate}$")
        self.assertNotRegex(self.weekly_jobs["dbt-oss"], r"(?m)^    if:")
        for name, job in self.weekly_jobs.items():
            with self.subTest(name):
                self.assertRegex(job, r"(?m)^    timeout-minutes: 30$")

    def test_saves_no_cache_and_keeps_no_credentials(self):
        allowed = {
            "actions/checkout",
            "cachix/install-nix-action",
            "nix-community/cache-nix-action",
            "actions/cache/restore",
        }
        for name, job in self.weekly_jobs.items():
            with self.subTest(name):
                used = re.findall(r"uses: ([^@\s]+)@", job)
                self.assertEqual(sorted(used), sorted(allowed))
                self.assertEqual(
                    job.count("          save: false\n"), used.count("nix-community/cache-nix-action")
                )
                self.assertRegex(
                    job,
                    r"uses: actions/checkout@\S+ # \S+\n {8}with:\n {10}persist-credentials: false\n",
                )
                blocks = re.findall(r"path: \|\n((?: {12}.*\n)+)", job)
                self.assertEqual([block.split() for block in blocks], [CARGO_CACHE])

    def test_fetches_the_latest_then_cuts_the_network_before_the_corpus(self):
        for name, build in (("dbt-oss", "oss"), ("dbt", "proprietary")):
            with self.subTest(name):
                job = self.weekly_jobs[name]
                steps = [
                    f"run: python3 scripts/fetch-dbt --latest {build} ",
                    "      - run: sudo sysctl -w kernel.apparmor_restrict_unprivileged_userns=0\n",
                    "run: unshare -rn true\n",
                    "      - run: nix develop -c make conformance ",
                ]
                places = [job.find(step) for step in steps]
                self.assertNotIn(-1, places)
                self.assertEqual(places, sorted(places))

    def test_the_proprietary_live_test_runs_cut_off_after_its_build_whatever_the_corpus_said(self):
        job = self.weekly_jobs["dbt"]
        self.assertIn(
            "      - id: fetch\n        run: python3 scripts/fetch-dbt --latest proprietary ", job
        )
        self.assertIn("      - id: cut\n        run: unshare -rn true\n", job)
        outcomes = "steps.fetch.outcome == 'success' && steps.cut.outcome == 'success'"
        condition = f"if: ${{{{ !cancelled() && {outcomes} }}}}"
        for step in (
            "run: nix develop -c cargo test --locked --test proxy --no-run",
            "run: nix develop -c unshare -rn make live ",
        ):
            with self.subTest(step):
                self.assertIn(f"      - {condition}\n        {step}", job)
        corpus = job.index("run: nix develop -c make conformance ")
        built = job.index("run: nix develop -c cargo test --locked --test proxy --no-run")
        self.assertLess(corpus, built)
        self.assertLess(built, job.index("run: nix develop -c unshare -rn make live "))

    def test_every_pipe_fails_with_its_command(self):
        self.assertRegex(self.weekly, r"(?m)^defaults:\n  run:\n    shell: bash\n")
        self.assertEqual(self.weekly.count("shell:"), 1)

    def test_each_job_ends_with_its_summary_of_what_it_found(self):
        for name, job in self.weekly_jobs.items():
            with self.subTest(name):
                last = job[job.rindex("      - ") :]
                self.assertTrue(last.startswith("      - if: always()\n        run: |\n"), last)
                self.assertIn('>> "$GITHUB_STEP_SUMMARY"', last)
                for log in ("fetch", "corpus"):
                    self.assertIn(f'| tee "$RUNNER_TEMP/{log}.log"', job)
                    self.assertIn(f'"$RUNNER_TEMP/{log}.log"', last)
                self.assertIn("grep -h '^conformance:' \"$RUNNER_TEMP/corpus.log\"", last)
                self.assertIn(
                    "sed -n '/panicked at/,/^note: run with/p' \"$RUNNER_TEMP/corpus.log\"", last
                )

    def test_github_s_listing_gets_the_job_s_token(self):
        fetch = re.search(
            r"run: python3 scripts/fetch-dbt --latest oss .*\n((?:        .*\n)*)", self.weekly
        )
        self.assertIn("GH_TOKEN: ${{ github.token }}", fetch[1])


