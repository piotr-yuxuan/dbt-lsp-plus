class NextVersion(unittest.TestCase):
    def test_table(self):
        for current, bump, expected in (
            ("0.1.0", "patch", "0.1.1"),
            ("1.2.3", "patch", "1.2.4"),
            ("1.2.3", "minor", "1.3.0"),
            ("1.2.3", "major", "2.0.0"),
            ("9.9.9", "patch", "9.9.10"),
        ):
            with self.subTest(current=current, bump=bump):
                self.assertEqual(release.next_version(current, ["0.0.0-other"], bump), expected)

    def test_never_gives_a_version_with_a_tag(self):
        with self.assertRaises(release.ReleaseError):
            release.next_version("1.2.3", ["1.2.4"], "patch")


class CurrentVersion(unittest.TestCase):
    def test_reads_this_repository_s_own_files(self):
        found = {path: (ROOT / path).read_bytes() for path in ("Cargo.toml", "Cargo.lock")}
        self.assertRegex(release.current_version(found), r"\A[0-9]+\.[0-9]+\.[0-9]+\Z")

    def test_reads_the_version_that_both_files_hold(self):
        found = {**texts("1.2.3"), "Cargo.lock": lock("1.2.3", other="9.9.9").encode()}
        self.assertEqual(release.current_version(found), "1.2.3")

    def test_refuses_what_is_not_a_version(self):
        for version in ("", "1.2", "01.2.3", "v1.2.3", "1.2.3-rc", "١.2.3"):
            with self.subTest(version=version), self.assertRaises(release.ReleaseError):
                release.current_version(texts(version))

    def test_refuses_files_that_disagree(self):
        with self.assertRaisesRegex(release.ReleaseError, "Cargo.lock"):
            release.current_version(texts("1.2.3", locked="1.2.4"))

    def test_refuses_a_file_without_one_version_of_the_package(self):
        no_package_version = manifest("1.2.3").replace('version = "1.2.3"\n', "")
        twice = lock("1.2.3") + lock("1.2.3").split("\n\n", 2)[2]
        for path, text in (
            ("Cargo.toml", no_package_version),
            ("Cargo.lock", lock("1.2.3").replace('name = "dbt-lsp-plus"', 'name = "other"')),
            (
                "Cargo.lock",
                lock("1.2.3").replace("dependencies = [", 'source = "git+x"\ndependencies = ['),
            ),
            ("Cargo.lock", twice),
        ):
            with self.subTest(path=path, text=text), self.assertRaisesRegex(release.ReleaseError, path):
                release.current_version({**texts("1.2.3"), path: text.encode()})


