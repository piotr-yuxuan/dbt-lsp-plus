def manifest(version):
    """A Cargo.toml at `version`, with a dependency whose own `version` key is not it."""
    return (
        f'[package]\nname = "dbt-lsp-plus"\nversion = "{version}"\nedition = "2024"\n\n'
        '[dependencies]\nregex = "1.13.1"\n\n[dependencies.url]\nversion = "2.5.8"\n'
    )


def lock(version, other="0.1.0"):
    """A Cargo.lock whose package is at `version`, beside a dependency at `other`."""
    return (
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n"
        f'[[package]]\nname = "aho-corasick"\nversion = "{other}"\n'
        'source = "registry+https://github.com/rust-lang/crates.io-index"\n\n'
        f'[[package]]\nname = "dbt-lsp-plus"\nversion = "{version}"\ndependencies = [\n "regex",\n]\n'
    )


def texts(version, locked=None):
    """The two version files at `version`, Cargo.lock at `locked` if given, as bytes by path."""
    return {"Cargo.toml": manifest(version).encode(), "Cargo.lock": lock(locked or version).encode()}


