def commit(name, parents=("p",), message="Add a thing", changed=("docs/page.md",)):
    return release.Commit(name, tuple(parents), message, frozenset(changed))


VERSION_MESSAGE = "Version 1.2.4\n\n[skip ci]"
VERSION_COMMIT = commit("made", ("c",), VERSION_MESSAGE, ("Cargo.toml", "Cargo.lock"))


class Decide(unittest.TestCase):
    """What a run decides, from what it finds, and with no input or output."""

    def test_table(self):
        c = commit("c")
        h = commit("h")
        for name, head, pending, released, tags, expected in (
            ("at the commit", c, None, False, {}, ("1.2.4", "c", None)),
            ("moved, no version commit", h, None, False, {}, (None, None, None)),
            ("moved, cut short", h, VERSION_COMMIT, False, {}, ("1.2.4", "c", "made")),
            ("moved, tag on it", h, VERSION_COMMIT, False, {"1.2.4": "made"}, ("1.2.4", "c", "made")),
            ("moved, released", h, VERSION_COMMIT, True, {"1.2.4": "made"}, (None, None, None)),
        ):
            with self.subTest(name):
                found = release.Found(c, head, pending, released, texts("1.2.3"), tags)
                decision = release.decide(found, "patch")
                self.assertEqual((decision.version, decision.base, decision.made), expected)

    def test_at_a_version_commit(self):
        made = VERSION_COMMIT
        finish = release.decide(release.Found(made, made, made, False, texts("1.2.4"), {}), "major")
        self.assertEqual((finish.version, finish.base, finish.made), ("1.2.4", "c", "made"))
        found = release.Found(made, made, made, True, texts("1.2.4"), {"1.2.4": "made"})
        raised = release.decide(found, "major")
        self.assertEqual((raised.version, raised.base, raised.made), ("2.0.0", "made", None))

    def test_a_tag_on_another_commit_stops_it(self):
        found = release.Found(
            commit("c"), commit("h"), VERSION_COMMIT, False, texts("1.2.3"), {"1.2.4": "o"}
        )
        with self.assertRaises(release.ReleaseError):
            release.decide(found, "patch")

    def test_nothing_to_do_reads_no_version(self):
        found = release.Found(commit("c"), commit("h"), None, False, texts("banana"), {})
        self.assertIsNone(release.decide(found, "patch").version)

    def test_what_is_a_version_commit(self):
        both = ("Cargo.toml", "Cargo.lock")
        for name, candidate, expected in (
            ("both files", VERSION_COMMIT, "1.2.4"),
            ("Cargo.toml alone", commit("x", ("p",), VERSION_MESSAGE, ("Cargo.toml",)), None),
            ("Cargo.lock alone", commit("x", ("p",), VERSION_MESSAGE, ("Cargo.lock",)), None),
            ("another file", commit("x", ("p",), VERSION_MESSAGE, (*both, "docs/page.md")), None),
            ("a merge", commit("x", ("p", "q"), VERSION_MESSAGE, both), None),
            ("no marker", commit("x", ("p",), "Version 1.2.4", both), None),
            ("more text", commit("x", ("p",), VERSION_MESSAGE + "\n\nMore.", both), None),
            ("not a version", commit("x", ("p",), "Version 1.2\n\n[skip ci]", both), None),
        ):
            with self.subTest(name):
                self.assertEqual(release.written_version(candidate), expected)


